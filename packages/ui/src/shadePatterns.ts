/** The darkest step is 0, the lightest `SHADE_LEVELS - 1`. */
export const SHADE_LEVELS = SHADE_PATTERNS.length;

/** The step for a brightness from 0 (black) to 1 (white). */
export function shadeLevel(brightness: number): number {
  const level = Math.floor(brightness * (SHADE_LEVELS - 0.01));
  return level < 0 ? 0 : level >= SHADE_LEVELS ? SHADE_LEVELS - 1 : level;
}

/** Ink at device pixel `(x, y)` for a step: 1 = black, 0 = white, the `blitPixels` contract. */
export function shadeInk(level: number, x: number, y: number): 0 | 1 {
  return (SHADE_PATTERNS[level]![y & 7]! >> (7 - (x & 7))) & 1 ? 0 : 1;
}
