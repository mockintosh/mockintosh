#!/usr/bin/env python3
"""Bake the System 6.0.8 city fonts into Mockintosh `%%MFN1` faces.

Reads Venice, London, Athens, San Francisco, Cairo and Los Angeles from the
Fonts suitcase in Font/DA Mover Folder on the System 6.0.8 System Additions
disk, every plain size each FOND lists. Like `import-system-fonts.py`, every
glyph Apple drew comes across keyed by its Unicode character (Mac OS Roman),
with each strike's own missing-character box, Apple's advances and kerning.
The cell is Apple's whole font rectangle.

Toronto isn't on any System 6 disk (it was dropped before 6.0). Pass a
suitcase that has it with `--toronto`; without one, the Toronto strikes
already in `faces/city/` are kept as they are.

The disk image is not committed. Default source:

  /tmp/system608/MacOS_6.0.8_System_Additions.img

Usage:
  python3 scripts/import-city-fonts.py
  python3 scripts/import-city-fonts.py --image /path/to/System_Additions.img [--toronto /path/to/suitcase]

Needs `pip install machfs rsrcfork`.
"""

from __future__ import annotations

import argparse
import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "packages/ui/src/fonts/faces/city"
DEFAULT_IMAGE = Path("/tmp/system608/MacOS_6.0.8_System_Additions.img")

_spec = importlib.util.spec_from_file_location("import_system_fonts", ROOT / "scripts/import-system-fonts.py")
sysfonts = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sysfonts)

# FOND family → registry key.
FAMILIES = {
    "Venice": "venice",
    "London": "london",
    "Athens": "athens",
    "San Francisco": "sanFrancisco",
    "Cairo": "cairo",
    "Los Angeles": "losAngeles",
}
TORONTO = "toronto"


def const_name(family: str, size: int) -> str:
    return f"CITY_FONT_{re.sub(r'([a-z])([A-Z])', r'\1_\2', family).upper()}_{size}"


def bake(raw: bytes, high: str) -> tuple[str, dict, int]:
    font = sysfonts.parse_nfnt(raw)
    glyphs: list[dict] = []
    have: set[int] = set()
    for code in range(font["first"], font["last"] + 2):
        missing = code == font["last"] + 1
        cp = sysfonts.MISSING_CODE if missing else sysfonts.code_point_for(code, high)
        if cp is None or cp in have:
            continue
        glyph = sysfonts.nfnt_glyph(font, code - font["first"], 0)
        if glyph is None:
            continue
        glyph["codePoint"] = cp
        glyphs.append(glyph)
        have.add(cp)
    record = sysfonts.encode(font["height"], 0, 0, 0, glyphs)
    info = {"ascent": font["ascent"], "descent": font["descent"], "leading": font["leading"]}
    return record, info, len(glyphs)


def suitcase_strikes(rf, families: dict[str, str]) -> list[tuple[str, str, int, int]]:
    """(FOND name, family key, size, resource ID) for each plain strike."""
    out = []
    for fond_name, family in families.items():
        for size, style, rid in sysfonts.fond_sizes(rf, fond_name):
            if style == 0 and sysfonts.has_font(rf, rid):
                out.append((fond_name, family, size, rid))
    return out


def write_strike(family: str, size: int, record: str, info: dict, source: str, count: int) -> None:
    (OUT_DIR / f"{family}_{size}.ts").write_text(
        f"// Generated from {source}. Do not hand-edit.\n"
        f"//   python3 scripts/import-city-fonts.py\n"
        f"//\n"
        f"// FONT header: ascent {info['ascent']}, descent {info['descent']}, leading {info['leading']}.\n"
        f"// {count} glyphs.\n"
        f'export const {const_name(family, size)} = "{record}";\n',
        encoding="utf-8",
    )


def kept_toronto() -> list[tuple[str, int, dict]]:
    """The Toronto strikes already committed, with the FONT header their comment records."""
    kept = []
    for path in sorted(OUT_DIR.glob(f"{TORONTO}_*.ts")):
        text = path.read_text(encoding="utf-8")
        header = re.search(r"ascent (\d+), descent (\d+), leading (\d+)", text)
        if not header or not text.count("%%MFN1"):
            raise SystemExit(f"{path.name}: expected an %%MFN1 strike with its FONT header comment")
        ascent, descent, leading = map(int, header.groups())
        kept.append((TORONTO, int(path.stem.split("_")[1]), {"ascent": ascent, "descent": descent, "leading": leading}))
    return kept


def write_generated(entries: list[tuple[str, int, dict]]) -> None:
    lines = ["// Generated by scripts/import-city-fonts.py. Do not hand-edit.", ""]
    for family, size, _ in entries:
        lines.append(f'import {{ {const_name(family, size)} }} from "./{family}_{size}";')
    lines += [
        "",
        "export interface CityStrike {",
        "  family: string;",
        "  size: number;",
        "  data: string;",
        "  info: { ascent: number; descent: number; leading: number };",
        "}",
        "",
        "/** Venice, London, Athens, San Francisco, Toronto, Cairo and Los Angeles. */",
        "export const CITY_GENERATED: readonly CityStrike[] = [",
    ]
    for family, size, info in entries:
        lines.append(
            f'  {{ family: "{family}", size: {size}, data: {const_name(family, size)}, info: {{ ascent: {info["ascent"]}, descent: {info["descent"]}, leading: {info["leading"]} }} }},'
        )
    lines += ["];", ""]
    (OUT_DIR / "generated.ts").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--image", type=Path, default=DEFAULT_IMAGE, help="System 6.0.8 System Additions disk image")
    parser.add_argument("--toronto", type=Path, help="a suitcase (resource fork) with Toronto")
    args = parser.parse_args()
    high = sysfonts.mac_roman_high()
    volume = sysfonts.read_volume(args.image)
    suitcase = sysfonts.open_rsrc(volume["Font/DA Mover Folder"]["Fonts"].rsrc)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    sources = [(suitcase, FAMILIES, "System 6.0.8 Fonts")]
    if args.toronto:
        sources.append((sysfonts.open_rsrc(args.toronto.read_bytes()), {"Toronto": TORONTO}, args.toronto.name))
    entries = []
    for rf, families, label in sources:
        for fond_name, family, size, rid in suitcase_strikes(rf, families):
            record, info, count = bake(sysfonts.font_resource([rf], rid), high)
            write_strike(family, size, record, info, f"{label} FONT {rid} ({fond_name} {size})", count)
            entries.append((family, size, info))
            print(f"{family}_{size}: {count} glyphs")
    if not args.toronto:
        entries += kept_toronto()
    entries.sort(key=lambda e: (e[0], e[1]))
    write_generated(entries)


if __name__ == "__main__":
    main()
